-- ─── 4) CHECKs and partial unique indexes ─────────────────────────
--
-- ADR 0002 §6: a relation never joins an item to itself; RELATES is stored
-- once, smaller id first (compared byte-wise, as the usecase compares with
-- JavaScript `<`); an item duplicates at most one item.
ALTER TABLE "WorkItemRelation" ADD CONSTRAINT "WorkItemRelation_not_self"
    CHECK ("fromId" <> "toId");
ALTER TABLE "WorkItemRelation" ADD CONSTRAINT "WorkItemRelation_relates_ordered"
    CHECK ("type" <> 'RELATES' OR "fromId" < "toId" COLLATE "C");
CREATE UNIQUE INDEX "WorkItemRelation_one_duplicate_target"
    ON "WorkItemRelation"("tenantId", "fromId") WHERE "type" = 'DUPLICATES';

-- ADR 0002 §3: a team has exactly one default state for new items.
CREATE UNIQUE INDEX "WorkflowState_one_default_per_team"
    ON "WorkflowState"("tenantId", "teamId") WHERE "isDefault";

