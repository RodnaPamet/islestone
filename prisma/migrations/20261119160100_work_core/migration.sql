-- ─── 2) Grants ────────────────────────────────────────────────────
--
-- The key bookkeeping (`ProjectKeyPrefix`, `ProjectKeySequence`,
-- `WorkItemKeyAlias`) is never deleted by the application: prefixes and
-- numbers are never reused and old keys keep resolving. The REVOKE is
-- explicit because a database's default privileges (prisma/init-roles.sh)
-- may already have granted more. The other tables are deleted by the purge
-- job (`work-item-purge`) inside each workspace's context.
GRANT SELECT, INSERT, UPDATE ON "ProjectKeyPrefix", "ProjectKeySequence", "WorkItemKeyAlias" TO app_user;
REVOKE DELETE, TRUNCATE ON "ProjectKeyPrefix", "ProjectKeySequence", "WorkItemKeyAlias" FROM app_user;
GRANT SELECT, INSERT, UPDATE, DELETE ON "Team", "WorkflowState", "Project", "WorkItemType", "WorkItem", "WorkItemRelation", "Label", "WorkItemLabel", "Comment", "WorkItemWatcher", "WorkItemLink" TO app_user;

