-- ─── 5) A workflow state's category never changes ─────────────────
--
-- ADR 0002 §3: to recategorise, create a new state and move the items. This
-- is what lets `WorkItem.stateCategory` be held by the composite foreign key
-- to `WorkflowState(id, teamId, category, tenantId)`: with the category
-- fixed, no cascade or stale copy is possible.
CREATE OR REPLACE FUNCTION workflow_state_category_immutable()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW."category" IS DISTINCT FROM OLD."category" THEN
        RAISE EXCEPTION 'WORKFLOW_STATE_CATEGORY_IMMUTABLE: a workflow state''s category never changes (ADR 0002 section 3)'
            USING ERRCODE = 'P0001';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER workflow_state_category_immutable
    BEFORE UPDATE OF "category" ON "WorkflowState"
    FOR EACH ROW EXECUTE FUNCTION workflow_state_category_immutable();

